function links(c: LegalContext) {
  const email: Inline | null = c.legal.email ? { text: c.legal.email, href: `mailto:${c.legal.email}` } : null;
  const phone: Inline = { text: c.contacts.phoneDisplay, href: `tel:${c.contacts.phoneTel}` };
  return { email, phone };
}

